export async function quickMealDbChecks(db, ids, ok) {
  const { coach: C, ana: A, bo: B } = ids
  async function as(who, query, params = []) {
    await db.exec('reset role')
    await db.query("select set_config('request.jwt.claims', $1, false)", [who ? JSON.stringify({ sub: who, role: 'authenticated' }) : ''])
    await db.exec(who ? 'set role authenticated' : 'set role anon')
    try { return { rows: (await db.query(query, params)).rows } }
    catch (e) { return { error: e.message } }
    finally { await db.exec('reset role') }
  }
  const items = JSON.stringify([{ name: 'Porridge', amount_label: '1 bowl', kcal: 300, protein: 15, carbs: 40, fat: 9 }])
  const insert = (who, client, name = 'Breakfast test', value = items) => as(who,
    'insert into saved_meals(client_id,name,items) values ($1,$2,$3::jsonb) returning id', [client, name, value])
  const saved = await insert(A, A)
  ok(!saved.error && saved.rows.length === 1, 'saved meals: client creates own snapshot')
  const id = saved.rows[0].id
  ok(!!(await insert(A, A)).error, 'saved meals: duplicate name rejected')
  ok(!(await insert(B, B)).error, 'saved meals: same name allowed for another client')
  ok(!!(await insert(A, B, 'Spoofed')).error, 'saved meals: cannot save for another client')
  ok((await as(B, 'select * from saved_meals where id=$1', [id])).rows.length === 0, 'saved meals: other client cannot read snapshot')
  ok((await as(C, 'select * from saved_meals where id=$1', [id])).rows.length === 1, 'saved meals: coach can read snapshot')
  ok(!!(await as(null, 'select * from saved_meals')).error, 'saved meals: anonymous read denied')
  ok(!!(await insert(null, A, 'Anonymous')).error, 'saved meals: anonymous insert denied')
  ok(!!(await as(A, 'update saved_meals set client_id=$1 where id=$2', [B, id])).error, 'saved meals: ownership cannot be changed')
  ok((await as(B, 'delete from saved_meals where id=$1 returning id', [id])).rows.length === 0, 'saved meals: cannot remove another client snapshot')
  ok((await as(C, 'delete from saved_meals where id=$1 returning id', [id])).rows.length === 0, 'saved meals: coach cannot remove client snapshot')
  ok(!!(await insert(A, A, 'Empty', '[]')).error, 'saved meals: empty snapshot rejected')
  ok(!!(await insert(A, A, 'Object', '{}')).error, 'saved meals: snapshot must be an array')
  ok(!!(await insert(A, A, ' ')).error, 'saved meals: blank name rejected')
  ok(!!(await insert(A, A, 'x'.repeat(81))).error, 'saved meals: long name rejected')
  ok((await as(A, 'delete from saved_meals where id=$1 returning id', [id])).rows.length === 1, 'saved meals: client removes own snapshot')
  // Verify account cleanup without changing the fixtures used by existing checks.
  const disposable = '44444444-4444-4444-4444-444444444444'
  await db.query("insert into auth.users(id,email) values ($1,'saved-meal-test@x.com')", [disposable])
  const temp = await insert(disposable, disposable)
  await db.query('delete from auth.users where id=$1', [disposable])
  ok((await db.query('select id from saved_meals where id=$1', [temp.rows[0].id])).rows.length === 0, 'saved meals: deleting account cascades snapshots')
  await db.query('delete from saved_meals where client_id=$1', [B])
}

export async function quickMealBrowserChecks({ open, sql, IDS, BASE, shot, clean, ok }) {
  const day = new Date().toLocaleDateString('en-CA')
  const yesterdayDate = new Date(day + 'T12:00:00'); yesterdayDate.setDate(yesterdayDate.getDate() - 1)
  const yesterday = yesterdayDate.toLocaleDateString('en-CA')
  // Dedicated fixture names keep these checks independent of the other diary flows.
  await sql('delete from food_logs where client_id=$1 and date=$2 and meal_type=$3', [IDS.ana, yesterday, 'breakfast'])
  await sql("insert into food_logs(client_id,date,meal_type,name,amount_label,kcal,protein,carbs,fat) values ($1,$2,'breakfast','Quick oats fixture','80 g',300,12,50,6),($1,$2,'breakfast','Quick milk fixture','200 ml',100,7,10,3)", [IDS.ana, yesterday])
  const { ctx, page, errors } = await open('ana')
  await page.goto(BASE + '/nutrition', { waitUntil: 'networkidle' })
  const existing = (await sql("select count(*)::int n from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].n
  const copyButton = page.getByRole('button', { name: 'Copy previous day breakfast', exact: true })
  await copyButton.click()
  const preview = page.getByRole('dialog', { name: 'Copy previous breakfast', exact: true })
  await preview.getByText('Quick oats fixture', { exact: true }).waitFor()
  ok((await sql("select count(*)::int n from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].n === existing, 'quick meals: preview does not write to diary')
  await preview.getByRole('button', { name: 'Close', exact: true }).click()
  ok((await sql("select count(*)::int n from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].n === existing, 'quick meals: cancelling copy leaves diary unchanged')
  await copyButton.click()
  await preview.getByText('Quick oats fixture', { exact: true }).waitFor()
  await shot(page, 'quick-meal-copy-preview-phone')
  await preview.getByRole('button', { name: 'Add copied meal', exact: true }).click()
  await page.getByText('Previous meal added.', { exact: true }).waitFor()
  await page.getByText('Quick oats fixture', { exact: true }).waitFor()
  const copied = await sql("select * from food_logs where client_id=$1 and date=$2 and meal_type='breakfast' and name in ('Quick oats fixture','Quick milk fixture')", [IDS.ana, day])
  ok(copied.length === 2, 'quick meals: copy logs both entries on selected date')
  ok(copied.reduce((n, x) => n + Number(x.kcal), 0) === 400 && copied.find(x => x.name === 'Quick oats fixture').amount_label === '80 g', 'quick meals: copied portions and macros preserved')
  ok((await sql("select count(*)::int n from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].n === existing + 2, 'quick meals: existing diary entries preserved')
  await page.getByRole('button', { name: 'Save breakfast as a meal', exact: true }).click()
  const save = page.getByRole('dialog', { name: 'Save breakfast', exact: true })
  await save.getByLabel('Saved meal name').fill('Busy morning breakfast')
  await save.getByRole('button', { name: 'Save meal', exact: true }).click()
  await page.getByText('Meal saved. Find it under Add, then Saved meals.', { exact: true }).waitFor()
  const stored = (await sql('select * from saved_meals where client_id=$1 and name=$2', [IDS.ana, 'Busy morning breakfast']))[0]
  ok(stored.items.length === existing + 2 && stored.items.every(x => !('id' in x) && !('client_id' in x) && !('date' in x)), 'quick meals: saved snapshot excludes source identifiers')
  ok((await sql("select count(*)::int n from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].n === existing + 2, 'quick meals: saving does not log again')
  await page.reload({ waitUntil: 'networkidle' })
  const breakfast = page.locator('.card').filter({ has: page.getByRole('button', { name: 'Copy previous day breakfast', exact: true }) })
  await breakfast.getByRole('button', { name: 'Add', exact: true }).click()
  const add = page.getByRole('dialog', { name: 'Add to breakfast', exact: true })
  await add.getByRole('tab', { name: 'Saved meals', exact: true }).click()
  await add.getByRole('button', { name: /Busy morning breakfast/ }).click()
  await add.getByRole('button', { name: 'Add saved meal', exact: true }).waitFor()
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'quick meals: saved meal picker fits phone width')
  await shot(page, 'quick-meal-saved-preview-phone')
  await add.getByRole('button', { name: 'Add saved meal', exact: true }).click()
  await add.waitFor({ state: 'hidden' })
  ok((await sql("select count(*)::int n from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].n === (existing + 2) * 2, 'quick meals: saved meal logs all entries')
  const mealTotal = (await sql("select sum(kcal) total from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].total
  await breakfast.getByRole('button', { name: 'Add', exact: true }).click()
  await add.getByRole('tab', { name: 'Saved meals', exact: true }).click()
  await add.getByRole('button', { name: /Busy morning breakfast/ }).click()
  await add.getByRole('button', { name: 'Remove saved meal', exact: true }).click()
  await add.getByRole('button', { name: 'Cancel removal', exact: true }).click()
  ok((await sql('select id from saved_meals where id=$1', [stored.id])).length === 1, 'quick meals: cancellation preserves saved meal')
  await add.getByRole('button', { name: 'Remove saved meal', exact: true }).click()
  await add.getByRole('button', { name: 'Confirm removal', exact: true }).click()
  await add.getByText('No saved meals yet.', { exact: true }).waitFor()
  ok((await sql('select id from saved_meals where id=$1', [stored.id])).length === 0, 'quick meals: client removes saved meal')
  ok(Number((await sql("select sum(kcal) total from food_logs where client_id=$1 and date=$2 and meal_type='breakfast'", [IDS.ana, day]))[0].total) === Number(mealTotal), 'quick meals: removing saved meal preserves diary history')
  await add.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Next day', exact: true }).click()
  ok(await page.getByRole('button', { name: /Copy previous day/ }).count() === 0 && await page.getByRole('button', { name: /Save .* as a meal/ }).count() === 0, 'quick meals: future plan pages do not offer diary shortcuts')
  clean('quick meal flows', errors)
  await ctx.close()
}