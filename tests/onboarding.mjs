export async function onboardingDbChecks(db, { coach: C, ana: A, bo: B }, ok) {
  async function as(who, query, params = []) {
    await db.exec('reset role')
    await db.query("select set_config('request.jwt.claims', $1, false)", [who ? JSON.stringify({ sub: who, role: 'authenticated' }) : ''])
    await db.exec(who ? 'set role authenticated' : 'set role anon')
    try { return { rows: (await db.query(query, params)).rows } } catch (e) { return { error: e.message } }
    finally { await db.exec('reset role') }
  }
  const insert = "insert into client_onboarding(client_id,goals,experience,equipment,preferred_days) values($1,'Build strength','beginner','Home, dumbbells',array[1,3,5]) returning *"
  ok(!!(await as(null, 'select * from client_onboarding')).error, 'onboarding: anonymous reads denied')
  ok(!!(await as(B, insert, [A])).error, 'onboarding: another client cannot submit answers')
  ok(!!(await as(C, insert, [A])).error, 'onboarding: coach cannot impersonate client submission')
  const created = await as(A, insert, [A])
  ok(created.rows?.length === 1 && !created.rows[0].training_ready, 'onboarding: client creates own profile with incomplete checklist')
  ok(!!(await as(A, insert, [A])).error, 'onboarding: one profile per client')
  ok((await as(A, 'select * from client_onboarding where client_id=$1', [A])).rows?.length === 1, 'onboarding: own answers readable')
  ok((await as(B, 'select * from client_onboarding where client_id=$1', [A])).rows?.length === 0, 'onboarding: answers private from other clients')
  ok((await as(C, 'select * from client_onboarding where client_id=$1', [A])).rows?.length === 1, 'onboarding: coach reads answers')
  ok((await as(B, "update client_onboarding set goals='Spoof' where client_id=$1 returning *", [A])).rows?.length === 0, 'onboarding: other client cannot update answers')
  ok((await as(C, "update client_onboarding set goals='Spoof' where client_id=$1 returning *", [A])).rows?.length === 0, 'onboarding: coach cannot rewrite client answers')
  ok(!!(await as(A, 'update client_onboarding set client_id=$1 where client_id=$2', [B, A])).error, 'onboarding: owner cannot transfer answers')
  for (const [sql, label] of [
    ["goals=' '", 'blank goals'], ["experience='expert-hacker'", 'unknown experience'],
    ["equipment=' '", 'blank equipment'], ["preferred_days=array[]::smallint[]", 'empty preferred days'],
    ["preferred_days=array[8]", 'invalid preferred day'], ["preferred_days=array[1,null]::smallint[]", 'null preferred day'],
    ["food_preferences=repeat('x',1201)", 'oversized preferences'],
  ]) ok(!!(await as(A, 'update client_onboarding set ' + sql + ' where client_id=$1', [A])).error, 'onboarding: rejects ' + label)
  ok((await as(A, "update client_onboarding set goals='Improve consistency', training_ready=true where client_id=$1 returning *", [A])).rows?.[0].training_ready === true, 'onboarding: owner updates answers and checklist')
  ok(!!(await as(A, 'delete from client_onboarding where client_id=$1', [A])).error, 'onboarding: no accidental profile deletion')
  await db.query('delete from client_onboarding where client_id=$1', [A])
  const temp = '44444444-4444-4444-4444-444444444444'
  await db.query("insert into auth.users(id,email,raw_user_meta_data) values($1,'onboarding@x.com','{}')", [temp])
  await db.query(insert, [temp])
  await db.query('delete from auth.users where id=$1', [temp])
  ok((await db.query('select * from client_onboarding where client_id=$1', [temp])).rows.length === 0, 'onboarding: account deletion cleans up setup')
}

export async function onboardingBrowserChecks({ open, sql, IDS, BASE, shot, clean, ok }) {
  await sql("insert into client_health(client_id,allergies,health_conditions,consent_data,consent_health,consent_accurate,consent_version,consented_at) values($1,'None','None',true,true,true,1,now())", [IDS.ana])
  const client = await open('ana')
  const { page } = client
  const setup = page.getByRole('region', { name: 'Coaching setup', exact: true })
  const start = setup.getByRole('button', { name: 'Start coaching setup', exact: true })
  await start.waitFor()
  ok(await page.getByRole('dialog').count() === 0, 'onboarding: optional setup does not block existing app')
  await page.route('**/rest/v1/client_onboarding*', route => route.request().method() === 'GET'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Offline"}' }) : route.continue())
  await page.reload({ waitUntil: 'networkidle' })
  await setup.getByRole('alert').waitFor()
  ok(await start.count() === 0, 'onboarding: failed read does not pretend profile is missing')
  await page.unroute('**/rest/v1/client_onboarding*')
  await setup.getByRole('button', { name: 'Retry coaching setup', exact: true }).click()
  await start.click()
  const form = page.getByRole('dialog', { name: 'Your coaching profile', exact: true })
  await form.getByLabel('What would you like to achieve?', { exact: true }).fill('Unsaved draft')
  await form.getByRole('button', { name: 'Close', exact: true }).click()
  ok((await sql('select * from client_onboarding where client_id=$1', [IDS.ana])).length === 0, 'onboarding: closing setup creates no partial record')
  await start.click()
  await form.getByLabel('What would you like to achieve?', { exact: true }).fill('Build strength for a busy working week.')
  await form.getByLabel('Training experience', { exact: true }).selectOption('returning')
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByLabel('Where will you train and what equipment is available?', { exact: true }).fill('Home with dumbbells and a gym at weekends.')
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByText('Describe your equipment and choose at least one preferred day.', { exact: true }).waitFor()
  ok(true, 'onboarding: routine requires a preferred day')
  await form.getByLabel('Wednesday', { exact: true }).check()
  await form.getByLabel('Monday', { exact: true }).check()
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'onboarding: routine form fits phone width')
  await shot(page, 'onboarding-routine-phone')
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByLabel('Food preferences (optional)', { exact: true }).fill('Vegetarian, quick meals for work.')
  await page.route('**/rest/v1/client_onboarding*', route => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Offline"}' }) : route.continue())
  await form.getByRole('button', { name: 'Save coaching profile', exact: true }).click()
  await form.getByRole('alert').waitFor()
  ok(await form.getByLabel('Food preferences (optional)', { exact: true }).inputValue() === 'Vegetarian, quick meals for work.', 'onboarding: failed save preserves answers')
  await page.unroute('**/rest/v1/client_onboarding*')
  await form.locator('form').evaluate(el => {
    el.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    el.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
  })
  await form.waitFor({ state: 'hidden' })
  await setup.getByText('Build strength for a busy working week.', { exact: false }).waitFor()
  const saved = (await sql('select * from client_onboarding where client_id=$1', [IDS.ana]))[0]
  ok(saved?.experience === 'returning' && saved.preferred_days.join(',') === '1,3', 'onboarding: answers and ordered days saved once')
  await page.reload({ waitUntil: 'networkidle' })
  await setup.getByText('Vegetarian, quick meals for work.', { exact: false }).waitFor()
  ok(await setup.getByRole('link', { name: 'View training', exact: true }).getAttribute('href') === '/train', 'onboarding: checklist links to existing training page')
  const training = setup.getByLabel('I have reviewed my training page', { exact: true })
  await page.route('**/rest/v1/client_onboarding*', route => route.request().method() === 'PATCH'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Offline"}' }) : route.continue())
  await training.click()
  await setup.getByText('Could not save checklist progress. Please retry when connected.', { exact: true }).waitFor()
  ok(!(await training.isChecked()), 'onboarding: failed checklist save keeps previous progress')
  await page.unroute('**/rest/v1/client_onboarding*')
  await training.click()
  await setup.getByText('Your first week · 1/3 complete', { exact: true }).waitFor()
  await setup.getByRole('button', { name: 'Update coaching profile', exact: true }).click()
  await form.getByLabel('What would you like to achieve?', { exact: true }).fill('Build lasting strength and consistency.')
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByRole('button', { name: 'Continue', exact: true }).click()
  await form.getByRole('button', { name: 'Save coaching profile', exact: true }).click()
  await form.waitFor({ state: 'hidden' })
  ok((await sql('select training_ready from client_onboarding where client_id=$1', [IDS.ana]))[0].training_ready, 'onboarding: profile edits preserve checklist progress')
  await setup.getByLabel('I have explored my food diary', { exact: true }).click()
  await setup.getByText('Your first week · 2/3 complete', { exact: true }).waitFor()
  await setup.getByLabel('I know how to contact my coach', { exact: true }).click()
  await setup.getByText('Your first week · 3/3 complete', { exact: true }).waitFor()
  ok(await setup.locator('details').getAttribute('open') === null, 'onboarding: finished checklist collapses')
  await shot(page, 'onboarding-complete-phone')
  await page.reload({ waitUntil: 'networkidle' })
  await setup.getByText('Your first week · 3/3 complete', { exact: true }).waitFor()
  ok(true, 'onboarding: completed checklist persists after reload')
  client.errors.splice(0, client.errors.length, ...client.errors.filter(e => !/503/.test(e)))
  clean('onboarding client', client.errors)
  await client.ctx.close()

  const coach = await open('coach', { w: 1280, h: 860 })
  await coach.page.goto(BASE + '/clients/' + IDS.ana, { waitUntil: 'networkidle' })
  const review = coach.page.getByRole('region', { name: 'Coaching setup', exact: true })
  await review.getByText('Build lasting strength and consistency.', { exact: false }).waitFor()
  ok(await review.getByRole('button').count() === 0 && await review.locator('input,textarea').count() === 0, 'onboarding: coach gets read-only answers')
  await shot(coach.page, 'onboarding-coach-desktop')
  await coach.page.setViewportSize({ width: 390, height: 844 })
  ok(await coach.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'onboarding: coach summary fits phone width')
  await shot(coach.page, 'onboarding-coach-phone')
  clean('onboarding coach', coach.errors)
  await coach.ctx.close()
  await sql('delete from client_onboarding where client_id=$1', [IDS.ana])
  await sql('delete from client_health where client_id=$1', [IDS.ana])
}
