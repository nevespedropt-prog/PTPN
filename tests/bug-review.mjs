export async function bugReviewChecks({ open, sql, IDS, BASE, shot, clean, ok }) {
  const { ctx, page, errors } = await open('ana')
  const today = new Date().toLocaleDateString('en-CA')
  const previous = new Date(today + 'T12:00:00'); previous.setDate(previous.getDate() - 1)
  const yesterday = previous.toLocaleDateString('en-CA')
  const fail = async (pattern, method) => page.route(pattern, route => route.request().method() === method
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Audit failure"}' }) : route.continue())
  const count = async (table, extra = '', params = []) => Number((await sql('select count(*)::int n from ' + table + ' where client_id=$1' + extra, [IDS.ana, ...params]))[0].n)

  // Progress: failed reads, invalid values, retained drafts and safe deletion.
  await fail('**/rest/v1/measurements*', 'GET')
  await page.goto(BASE + '/progress', { waitUntil: 'networkidle' })
  await page.getByText('Could not load measurements. Please try again when connected.', { exact: true }).waitFor()
  ok(await page.getByText('No entries yet.', { exact: true }).count() === 0, 'review: failed measurement read is not shown as empty history')
  await page.unroute('**/rest/v1/measurements*')
  await page.getByRole('button', { name: 'Retry measurements', exact: true }).click()
  await page.getByText('Loading measurements...', { exact: true }).waitFor({ state: 'hidden' })
  const beforeMeasurements = await count('measurements')
  const weight = page.getByPlaceholder('Weight kg'), fat = page.getByPlaceholder('Body fat %')
  await weight.fill('-1')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  ok(await weight.evaluate(e => e.validity.rangeUnderflow) && await count('measurements') === beforeMeasurements, 'review: negative measurement rejected')
  await weight.fill(''); await fat.fill('101')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  ok(await fat.evaluate(e => e.validity.rangeOverflow) && await count('measurements') === beforeMeasurements, 'review: body-fat percentage over 100 rejected')
  await fat.fill(''); await weight.fill('83.7')
  await fail('**/rest/v1/measurements*', 'POST')
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByText('Could not save this measurement. Your values are still here. Please try again when connected.', { exact: true }).waitFor()
  ok(await weight.inputValue() === '83.7', 'review: failed measurement save retains values')
  await page.unroute('**/rest/v1/measurements*')
  const measurementForm = page.locator('form').filter({ has: weight })
  await measurementForm.evaluate(form => {
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
  })
  await page.locator('tr').filter({ hasText: '83.7' }).waitFor()
  ok(await count('measurements') === beforeMeasurements + 1, 'review: rapid duplicate measurement submissions create one row')
  const measurementId = (await sql('select id from measurements where client_id=$1 and weight_kg=83.7 order by created_at desc limit 1', [IDS.ana]))[0].id
  const measurementRow = page.locator('tr').filter({ hasText: '83.7' })
  await measurementRow.getByRole('button', { name: 'Delete', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Delete measurement', exact: true })
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  ok((await sql('select id from measurements where id=$1', [measurementId])).length === 1, 'review: cancelling measurement deletion preserves data')
  await measurementRow.getByRole('button', { name: 'Delete', exact: true }).click()
  await fail('**/rest/v1/measurements*', 'DELETE')
  await confirmation.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
  await confirmation.getByText('Could not delete this measurement. Please try again when connected.', { exact: true }).waitFor()
  ok((await sql('select id from measurements where id=$1', [measurementId])).length === 1, 'review: failed measurement deletion keeps data visible')
  await page.unroute('**/rest/v1/measurements*')
  await confirmation.getByRole('button', { name: 'Confirm deletion', exact: true }).click()
  await confirmation.waitFor({ state: 'hidden' })
  ok((await sql('select id from measurements where id=$1', [measurementId])).length === 0, 'review: measurement deletion retry succeeds')

  // Workout creation must not navigate into an unscheduled orphan.
  await page.goto(BASE + '/train', { waitUntil: 'networkidle' })
  const beforeWorkouts = Number((await sql('select count(*)::int n from workouts where created_by=$1', [IDS.ana]))[0].n)
  await fail('**/rest/v1/client_workouts*', 'POST')
  await page.getByRole('button', { name: 'Build my own', exact: true }).click()
  await page.getByText('Could not schedule your workout. Please try again when connected.', { exact: true }).waitFor()
  ok(new URL(page.url()).pathname.endsWith('/train'), 'review: failed scheduling stays on Train')
  ok(Number((await sql('select count(*)::int n from workouts where created_by=$1', [IDS.ana]))[0].n) === beforeWorkouts, 'review: failed scheduling cleans up unused workout')
  await page.unroute('**/rest/v1/client_workouts*')

  // Nutrition reads and quick/planned/random writes must expose failures.
  await fail('**/rest/v1/food_logs*', 'GET')
  await page.goto(BASE + '/nutrition', { waitUntil: 'networkidle' })
  await page.getByText('Could not load this food diary. Please try again when connected.', { exact: true }).waitFor()
  ok(await page.getByText('Start your day', { exact: true }).count() === 0, 'review: failed diary read is not shown as an empty day')
  await page.unroute('**/rest/v1/food_logs*')
  await page.getByRole('button', { name: 'Retry food diary', exact: true }).click()
  await page.getByRole('heading', { name: /^Breakfast/ }).waitFor()
  const breakfast = page.locator('.card').filter({ has: page.getByRole('button', { name: 'Copy previous day breakfast', exact: true }) })
  await breakfast.getByRole('button', { name: 'Add', exact: true }).click()
  const add = page.getByRole('dialog', { name: 'Add to breakfast', exact: true })
  await add.getByRole('tab', { name: 'Quick add', exact: true }).click()
  await add.getByPlaceholder('What did you eat?').fill('Audit quick meal')
  await add.locator('input[type=number]').first().fill('250')
  await fail('**/rest/v1/food_logs*', 'POST')
  await add.getByRole('button', { name: 'Add entry', exact: true }).click()
  await add.getByText('Could not save this food entry. Your values are still here. Please try again when connected.', { exact: true }).waitFor()
  ok(await add.getByPlaceholder('What did you eat?').inputValue() === 'Audit quick meal', 'review: failed food save retains draft')
  await page.unroute('**/rest/v1/food_logs*')
  await add.locator('form').evaluate(form => {
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
  })
  await add.waitFor({ state: 'hidden' })
  ok(await count('food_logs', " and name='Audit quick meal'") === 1, 'review: rapid food submissions create one entry')
  await page.getByRole('button', { name: 'Remove Audit quick meal', exact: true }).waitFor()
  await fail('**/rest/v1/food_logs*', 'DELETE')
  await page.getByRole('button', { name: 'Remove Audit quick meal', exact: true }).click()
  await page.getByText('Could not remove this food entry. Please try again when connected.', { exact: true }).waitFor()
  ok(await count('food_logs', " and name='Audit quick meal'") === 1, 'review: failed food deletion preserves entry')
  await page.unroute('**/rest/v1/food_logs*')
  await page.getByRole('button', { name: 'Remove Audit quick meal', exact: true }).click()
  await page.getByRole('button', { name: 'Remove Audit quick meal', exact: true }).waitFor({ state: 'hidden' })

  const recipe = (await sql('select id,name from recipes where id not in (select recipe_id from food_logs where client_id=$1 and recipe_id is not null) limit 1', [IDS.ana]))[0]
  const weekday = ((new Date(today + 'T12:00:00').getDay() + 6) % 7) + 1
  const planId = (await sql("insert into meal_plan_items(client_id,day,meal_type,recipe_id,servings,sort) values($1,$2,'dinner',$3,1,99) returning id", [IDS.ana, weekday, recipe.id]))[0].id
  await page.reload({ waitUntil: 'networkidle' })
  const planned = page.locator('.food-row').filter({ has: page.getByText(recipe.name, { exact: true }) }).filter({ has: page.getByRole('button', { name: 'Log', exact: true }) }).first()
  await fail('**/rest/v1/food_logs*', 'POST')
  await planned.getByRole('button', { name: 'Log', exact: true }).click()
  await page.getByText('Could not log this meal. Your selection is still here. Please try again when connected.', { exact: true }).waitFor()
  ok(await count('food_logs', ' and recipe_id=$2', [recipe.id]) === 0, 'review: failed planned meal save shows error')
  await page.unroute('**/rest/v1/food_logs*')
  await planned.getByRole('button', { name: 'Log', exact: true }).click()
  await page.getByRole('button', { name: 'Remove ' + recipe.name, exact: true }).first().waitFor()
  ok(await count('food_logs', ' and recipe_id=$2', [recipe.id]) === 1, 'review: planned meal retry succeeds')
  await sql('delete from meal_plan_items where id=$1', [planId])

  await page.getByRole('button', { name: 'Random dinner idea', exact: true }).click()
  const random = page.getByRole('dialog', { name: 'Random dinner idea', exact: true })
  await fail('**/rest/v1/food_logs*', 'POST')
  await random.getByRole('button', { name: 'Add to dinner', exact: true }).click()
  await random.getByText('Could not log this meal. Your selection is still here. Please try again when connected.', { exact: true }).waitFor()
  ok(await random.isVisible(), 'review: failed random meal save keeps selection open')
  await page.unroute('**/rest/v1/food_logs*')
  await random.getByRole('button', { name: 'Add to dinner', exact: true }).click()
  await random.waitFor({ state: 'hidden' })

  // An older, slower date response must not replace the current diary.
  const previousId = (await sql("insert into food_logs(client_id,date,meal_type,name,kcal) values($1,$2,'breakfast','Audit previous day',100) returning id", [IDS.ana, yesterday]))[0].id
  await page.route('**/rest/v1/food_logs*', async route => {
    if (route.request().method() === 'GET' && new URL(route.request().url()).searchParams.get('date') === 'eq.' + yesterday) await new Promise(resolve => setTimeout(resolve, 700))
    return route.continue()
  })
  await page.getByRole('button', { name: 'Previous day', exact: true }).click()
  await page.getByRole('button', { name: 'Next day', exact: true }).click()
  await page.getByRole('heading', { name: /^Breakfast/ }).waitFor()
  await page.waitForTimeout(900) // allow the intentionally delayed previous-day response to arrive
  ok(await page.getByText('Audit previous day', { exact: true }).count() === 0, 'review: stale diary response cannot overwrite selected day')
  await page.unroute('**/rest/v1/food_logs*')
  await sql('delete from food_logs where id=$1', [previousId])

  // Photo metadata/storage failures remain visible and recoverable.
  await page.goto(BASE + '/progress', { waitUntil: 'networkidle' })
  await page.getByRole('tab', { name: 'Photos', exact: true }).click()
  await page.getByRole('button', { name: 'other', exact: true }).click()
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==', 'base64')
  const beforePhotos = await count('progress_photos')
  const beforeFiles = Number((await sql("select count(*)::int n from storage.objects where bucket_id='progress-photos'"))[0].n)
  await fail('**/rest/v1/progress_photos*', 'POST')
  await page.locator('input[type=file]').setInputFiles({ name: 'audit.png', mimeType: 'image/png', buffer: png })
  await page.getByText('Could not save your photo. Reload photos before trying again if your connection dropped.', { exact: true }).waitFor()
  ok(await count('progress_photos') === beforePhotos && Number((await sql("select count(*)::int n from storage.objects where bucket_id='progress-photos'"))[0].n) === beforeFiles, 'review: failed photo record save cleans up uploaded file')
  await page.unroute('**/rest/v1/progress_photos*')
  await page.locator('input[type=file]').setInputFiles({ name: 'audit.png', mimeType: 'image/png', buffer: png })
  await page.getByRole('button', { name: /^other photo from/ }).last().waitFor()
  const photo = (await sql("select id,path from progress_photos where client_id=$1 and pose='other' order by created_at desc limit 1", [IDS.ana]))[0]
  await page.getByRole('button', { name: /^other photo from/ }).last().click()
  const viewer = page.getByRole('dialog')
  await fail('**/storage/v1/object/progress-photos*', 'DELETE')
  await viewer.getByRole('button', { name: 'Delete photo', exact: true }).click()
  await viewer.getByText('Could not delete the photo file. Your photo entry is still here. Please try again.', { exact: true }).waitFor()
  ok((await sql('select id from progress_photos where id=$1', [photo.id])).length === 1, 'review: failed file deletion preserves photo entry')
  await page.unroute('**/storage/v1/object/progress-photos*')
  await fail('**/rest/v1/progress_photos*', 'DELETE')
  await viewer.getByRole('button', { name: 'Delete photo', exact: true }).click()
  await viewer.getByText('The photo file was removed, but its entry could not be deleted. Please retry Delete photo.', { exact: true }).waitFor()
  ok((await sql('select id from progress_photos where id=$1', [photo.id])).length === 1 && (await sql('select id from storage.objects where name=$1', [photo.path])).length === 0, 'review: partial photo deletion reports accurate state')
  await page.unroute('**/rest/v1/progress_photos*')
  await viewer.getByRole('button', { name: 'Delete photo', exact: true }).click()
  await viewer.waitFor({ state: 'hidden' })
  ok((await sql('select id from progress_photos where id=$1', [photo.id])).length === 0, 'review: partial photo deletion can be retried')
  ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'review: failure and retry controls fit phone width')
  await shot(page, 'bug-review-progress-phone')
  errors.splice(0, errors.length, ...errors.filter(e => /503/.test(e) === false))
  clean('bug review failure recovery', errors)
  await ctx.close()
}