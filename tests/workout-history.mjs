export async function workoutHistoryChecks({ open, sql, IDS, BASE, shot, clean, ok }) {
  console.log('Progress workouts tab')
  await sql("insert into client_health(client_id,allergies,health_conditions,consent_data,consent_health,consent_accurate,consent_version,consented_at) values($1,'None','None',true,true,true,1,now()) on conflict (client_id) do nothing", [IDS.ana])
  const lib = (await sql('select id, name from workouts where created_by is null order by name limit 2'))
  const mine = (await sql("insert into workouts(name, created_by) values('History own workout', $1) returning id", [IDS.ana]))[0].id
  const now = new Date()
  const today = now.toLocaleDateString('en-CA')
  const lastMonth = new Date(now.getFullYear(), now.getMonth(), 0).toLocaleDateString('en-CA')
  const log = JSON.stringify({ timer: { elapsed_sec: 2700, started_at: null, running: false }, items: { a: [{ reps: '10', kg: '20', done: true }, { reps: '10', kg: '20', done: true }, { reps: '10', kg: '20', done: false }] } })
  const ids = []
  const add = async (workout, date, rating, withLog) => ids.push((await sql("insert into client_workouts(client_id, workout_id, date, status, completed_at, rating, log) values($1,$2,$3,'done',$4,$5,$6::jsonb) returning id", [IDS.ana, workout, date, new Date().toISOString(), rating, withLog ? log : '{}']))[0].id)
  try {
    await add(lib[0].id, today, 5, true)
    await add(mine, today, null, false)
    await add(lib[1].id, lastMonth, null, false)
    const client = await open('ana', { w: 390, h: 844 })
    const { page } = client
    const name = d => new Date(d + 'T12:00:00').toLocaleDateString('en-GB', { month: 'long', year: 'numeric' })
    await page.goto(BASE + '/progress?progressTab=workouts', { waitUntil: 'networkidle' })
    const tabs = await page.getByRole('tab').allInnerTexts()
    ok(tabs.join(',') === 'Body,Strength,Photos,Workouts', 'workouts tab: Monthly is merged into Workouts: ' + tabs.join(','))
    const report = page.getByRole('region', { name: 'Workouts report', exact: true })
    await report.locator('.tile').first().waitFor()
    const tile = label => report.locator('.tile').filter({ hasText: label })
    ok(await tile('Workouts completed').getByText('2/2', { exact: true }).count() === 1, 'workouts tab: completed count for the month')
    ok(await tile('Time trained').getByText('45 min', { exact: false }).count() === 1 && await tile('Sets done').locator('.value').innerText() === '2', 'workouts tab: time and sets for the month')
    const bar = d => report.getByRole('button', { name: name(d) + ':', exact: false })
    await bar(today).waitFor()
    ok((await bar(today).getAttribute('aria-label')).endsWith('2 workouts') && (await bar(lastMonth).getAttribute('aria-label')).endsWith('1 workouts') && await bar(today).getAttribute('aria-pressed') === 'true', 'workouts tab: trend bars count each month and mark the open one')
    const box = report.locator('details.collapsible-card')
    ok(await box.count() === 1 && !(await box.evaluate(el => el.open)), 'workouts tab: the workout list is one minimised box')
    await box.locator('summary').click()
    const rows = box.getByRole('link')
    ok(await rows.count() === 2, 'workouts tab: opening the box lists the month\'s workouts')
    ok(await box.locator('.badge', { hasText: 'Own' }).count() === 1 && await box.locator('.badge', { hasText: 'Coach plan' }).count() === 1, 'workouts tab: each line says coach plan or own')
    const first = await box.innerText()
    ok(first.includes('45 min') && first.includes('2 sets') && first.includes('★'), 'workouts tab: time, sets and rating are shown')
    ok((await rows.first().getAttribute('href')).startsWith('/workout/'), 'workouts tab: a line opens the workout')
    await bar(lastMonth).click()
    await report.getByLabel('Report month', { exact: true }).evaluate((el, v) => el.value === v, lastMonth.slice(0, 7))
    await report.locator('details.collapsible-card').getByText('Workouts in ' + name(lastMonth)).waitFor()
    await report.locator('details.collapsible-card summary').click()
    ok(await report.locator('details.collapsible-card').getByRole('link').count() === 1, 'workouts tab: tapping an older bar opens that month')
    ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'workouts tab: fits phone width')
    await shot(page, 'progress-workouts-tab-phone')
    clean('workouts tab', client.errors); await client.ctx.close()
  } finally {
    for (const id of ids) await sql('delete from client_workouts where id=$1', [id])
    await sql('delete from workouts where id=$1', [mine])
    await sql('delete from client_health where client_id=$1', [IDS.ana])
  }
}
