export async function coachTrainingChecks({ open, sql, IDS, BASE, shot, clean, ok }) {
  const prefix = 'cf100000-0000-4000-8000-'
  const id = n => prefix + String(n).padStart(12, '0')
  const today = new Date().toLocaleDateString('en-CA')
  let context
  try {
    await sql("insert into workouts(id,name,created_by) values($1,'Training removal test',$2)", [id(1), IDS.coach])
    await sql("insert into workout_items(id,workout_id,exercise_name,sets) values($1,$2,'Test press',3)", [id(2), id(1)])
    for (const [n, status] of [[3, 'skipped'], [4, 'scheduled'], [5, 'done'], [6, 'skipped']]) {
      await sql('insert into client_workouts(id,client_id,workout_id,date,status) values($1,$2,$3,$4,$5)', [id(n), IDS.ana, id(1), today, status])
    }
    await sql("insert into exercise_videos(id,client_id,client_workout_id,workout_item_id,exercise_name,video_path) values($1,$2,$3,$4,'Test press',$5)", [id(7), IDS.ana, id(6), id(2), IDS.ana + '/' + id(7) + '/clip.webm'])
    context = await open('coach')
    const { page, errors } = context
    await page.goto(BASE + '/clients/' + IDS.ana + '?keep=1', { waitUntil: 'networkidle' })
    await page.getByRole('tab', { name: 'Training', exact: true }).click()
    const row = n => page.locator('.item').filter({ has: page.locator('a[href="/workout/' + id(n) + '"]') })
    await row(3).waitFor()
    ok(new URL(page.url()).searchParams.get('tab') === 'training' && new URL(page.url()).searchParams.get('keep') === '1', 'coach training tab is saved in URL without losing other parameters')
    await row(3).getByRole('link').click()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await row(3).waitFor()
    ok(await page.getByRole('tab', { name: 'Training', exact: true }).getAttribute('aria-selected') === 'true', 'workout back button returns to Training')
    await row(3).getByRole('link').click()
    await page.goBack({ waitUntil: 'networkidle' })
    await row(3).waitFor()
    ok(await page.getByRole('tab', { name: 'Training', exact: true }).getAttribute('aria-selected') === 'true', 'browser back also returns to Training')
    await page.reload({ waitUntil: 'networkidle' })
    await row(3).waitFor()
    ok(await page.getByRole('tab', { name: 'Training', exact: true }).getAttribute('aria-selected') === 'true', 'Training survives refresh')
    await page.getByRole('tab', { name: 'Nutrition', exact: true }).click()
    await page.reload({ waitUntil: 'networkidle' })
    ok(await page.getByRole('tab', { name: 'Nutrition', exact: true }).getAttribute('aria-selected') === 'true', 'other selected client tabs survive refresh')
    await page.getByRole('tab', { name: 'Training', exact: true }).click()
    await row(3).waitFor()
    ok(await row(3).getByRole('button', { name: 'Remove from schedule', exact: true }).count() === 1, 'coach can remove skipped sessions')
    ok(await row(5).getByRole('button', { name: 'Remove from schedule', exact: true }).count() === 0, 'completed history has no removal control')
    const dialog = page.getByRole('dialog', { name: 'Remove workout', exact: true })
    await row(3).getByRole('button').click()
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    ok((await sql('select id from client_workouts where id=$1', [id(3)])).length === 1, 'cancel keeps the skipped session')
    await row(3).getByRole('button').click()
    ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'coach removal confirmation fits phone width')
    await shot(page, 'coach-training-remove-phone')
    let deletes = 0
    await page.route('**/rest/v1/client_workouts*', async route => {
      if (route.request().method() !== 'DELETE') return route.continue()
      deletes++
      await new Promise(resolve => setTimeout(resolve, 150))
      return route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Test deletion failure"}' })
    })
    await dialog.getByRole('button', { name: 'Confirm removal', exact: true }).evaluate(b => { b.click(); b.click() })
    await dialog.getByText('Could not remove this workout. Please check your connection and try again.').waitFor()
    ok(deletes === 1 && (await sql('select id from client_workouts where id=$1', [id(3)])).length === 1, 'failed deletion retains session and prevents duplicate writes')
    await page.unroute('**/rest/v1/client_workouts*')
    await dialog.getByRole('button', { name: 'Confirm removal', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    ok((await sql('select id from client_workouts where id=$1', [id(3)])).length === 0 && await row(3).count() === 0, 'retry removes skipped session from database and list')
    ok((await sql('select id from workouts where id=$1', [id(1)])).length === 1 && (await sql('select id from client_workouts where id=$1', [id(5)])).length === 1, 'removal preserves workout definition and completed history')
    await row(6).getByRole('button').click()
    await dialog.getByRole('button', { name: 'Confirm removal', exact: true }).click()
    await dialog.getByText('This session has technique feedback. It cannot be removed here.').waitFor()
    ok((await sql('select id from exercise_videos where id=$1', [id(7)])).length === 1, 'technique feedback session is preserved')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await row(4).getByRole('button').click()
    await sql("update client_workouts set status='done' where id=$1", [id(4)])
    await dialog.getByRole('button', { name: 'Confirm removal', exact: true }).click()
    await dialog.getByText('This session has changed or is no longer available. Close and refresh the page.').waitFor()
    ok((await sql('select status from client_workouts where id=$1', [id(4)]))[0].status === 'done', 'session completed after confirmation opened cannot be deleted')
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.reload({ waitUntil: 'networkidle' })
    await row(5).waitFor()
    ok(await row(3).count() === 0, 'skipped session removal persists after refresh')
    errors.splice(0, errors.length, ...errors.filter(x => !x.includes('503')))
    clean('coach training removal and navigation', errors)
  } finally {
    await context?.ctx.close()
    await sql('delete from workouts where id=$1', [id(1)])
  }
}

export async function tabMemoryChecks({ open, sql, IDS, BASE, ok, clean }) {
  const coach = await open('coach')
  const selected = (page, name) => page.getByRole('tab', { name, exact: true }).getAttribute('aria-selected')
  try {
    const { page } = coach
    await page.goto(BASE + '/library', { waitUntil: 'networkidle' })
    await page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    await page.goto(BASE + '/account', { waitUntil: 'networkidle' })
    await page.goto(BASE + '/library', { waitUntil: 'networkidle' })
    ok(await selected(page, 'Exercises') === 'true', 'library tab survives navigation through another page')
    await page.getByRole('tab', { name: 'Programmes', exact: true }).click()
    await page.getByRole('link', { name: /^(Edit|View) and assign$/ }).first().click()
    const programmeUrl = page.url().split('?')[0]
    await page.getByRole('button', { name: 'Week 2', exact: true }).click()
    await page.goto(BASE + '/account', { waitUntil: 'networkidle' })
    await page.goto(programmeUrl, { waitUntil: 'networkidle' })
    await page.getByRole('button', { name: 'Week 2', exact: true }).waitFor()
    ok((await page.getByRole('button', { name: 'Week 2', exact: true }).getAttribute('class')).includes('on'), 'programme week tab survives leaving and returning')
    await page.getByRole('link', { name: 'Back', exact: true }).click()
    ok(await selected(page, 'Programmes') === 'true', 'programme builder back link restores Library Programmes')
    await page.goto(BASE + '/library?tab=workouts', { waitUntil: 'networkidle' })
    ok(await selected(page, 'Workouts') === 'true', 'explicit tab link overrides remembered tab')
    await page.goto(BASE + '/library?tab=invalid', { waitUntil: 'networkidle' })
    ok(await selected(page, 'Workouts') === 'true', 'invalid requested tab safely uses the default')
    await page.goto(BASE + '/clients/' + IDS.ana, { waitUntil: 'networkidle' })
    await page.getByRole('tab', { name: 'Progress', exact: true }).click()
    await page.getByRole('tab', { name: 'Photos', exact: true }).click()
    await page.goto(BASE + '/clients/' + IDS.bo, { waitUntil: 'networkidle' })
    ok(await selected(page, 'Overview') === 'true', 'one client tab does not overwrite another client')
    await page.goto(BASE + '/clients/' + IDS.ana, { waitUntil: 'networkidle' })
    ok(await selected(page, 'Progress') === 'true' && await selected(page, 'Photos') === 'true', 'nested client Progress and Photos tabs both survive navigation')
    await page.goto(BASE + '/clients/' + IDS.ana + '?reviewWeek=2026-10-19', { waitUntil: 'networkidle' })
    ok(await selected(page, 'Overview') === 'true', 'weekly review deep link still opens Overview despite a remembered Progress tab')
    clean('coach tab memory', coach.errors)
  } finally { await coach.ctx.close() }
  await sql("insert into client_health(client_id,allergies,health_conditions,consent_data,consent_health,consent_accurate,consent_version,consented_at) values($1,'None','None',true,true,true,1,now())", [IDS.ana])
  const client = await open('ana')
  let clientBuiltWorkout
  try {
    const { page } = client
    for (const [path, name] of [['/train', 'History'], ['/progress', 'Strength'], ['/community', 'Challenges']]) {
      await page.goto(BASE + path, { waitUntil: 'networkidle' })
      await page.getByRole('tab', { name, exact: true }).click()
      await page.goto(BASE + '/account', { waitUntil: 'networkidle' })
      await page.goto(BASE + path, { waitUntil: 'networkidle' })
      ok(await selected(page, name) === 'true', path + ' keeps the selected tab after returning')
      await page.reload({ waitUntil: 'networkidle' })
      ok(await selected(page, name) === 'true', path + ' keeps selected tab on refresh')
    }
    await page.goto(BASE + '/nutrition', { waitUntil: 'networkidle' })
    const add = () => page.locator('.card', { hasText: 'Breakfast' }).getByRole('button', { name: /^Add$/ }).first().click()
    await add()
    await page.getByRole('tab', { name: 'Quick add', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.goto(BASE + '/account', { waitUntil: 'networkidle' })
    await page.goto(BASE + '/nutrition', { waitUntil: 'networkidle' })
    await add()
    ok(await selected(page, 'Quick add') === 'true', 'food entry tab survives leaving Nutrition and reopening its sheet')
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 1280, height: 860 })
    await page.evaluate(() => Object.defineProperty(window, 'sessionStorage', { configurable: true, get() { throw new DOMException('Blocked', 'SecurityError') } }))
    for (const [path, name] of [['/train', 'History'], ['/progress', 'Photos'], ['/community', 'Challenges']]) {
      await page.locator('nav a[href="' + path + '"]').first().click()
      await page.getByRole('tab', { name, exact: true }).click()
      await page.locator('nav a[href="/account"]').first().click()
      await page.locator('nav a[href="' + path + '"]').first().click()
      await page.getByRole('tab', { name, exact: true, selected: true }).waitFor()
      ok(await selected(page, name) === 'true', path + ' retains its tab through menu navigation when storage is blocked')
    }
    // Client-facing detail returns must survive a refresh without storage/history state.
    await page.addInitScript(() => Object.defineProperty(window, 'sessionStorage', { configurable: true, get() { throw new DOMException('Blocked', 'SecurityError') } }))
    const today = new Date().toLocaleDateString('en-CA')
    const day = new Date(today + 'T12:00:00')
    day.setDate(day.getDate() + (day.getDay() === 1 ? 1 : -1))
    const selectedDate = day.toLocaleDateString('en-CA')
    const dateLabel = day.toLocaleDateString('en-GB', { weekday: 'long', day: 'numeric', month: 'long' })
    const earlier = new Date(today + 'T12:00:00'); earlier.setDate(earlier.getDate() - 2)
    const push = (await sql("select id from workouts where name='Push' limit 1"))[0].id
    const historyId = 'cf200000-0000-4000-8000-000000000001'
    const scheduleId = 'cf200000-0000-4000-8000-000000000002'
    const homeId = 'cf200000-0000-4000-8000-000000000003'
    for (const [id, date, status] of [[historyId, earlier.toLocaleDateString('en-CA'), 'done'], [scheduleId, selectedDate, 'scheduled'], [homeId, today, 'scheduled']]) {
      await sql('insert into client_workouts(id,client_id,workout_id,date,status) values($1,$2,$3,$4,$5)', [id, IDS.ana, push, date, status])
    }
    const reloadWithoutState = async () => {
      await page.evaluate(() => history.replaceState(null, '', location.href))
      await page.reload({ waitUntil: 'networkidle' })
    }
    await page.goto(BASE + '/train?tab=history', { waitUntil: 'networkidle' })
    await page.locator('a[href^="/workout/' + historyId + '"]').click()
    ok((new URL(page.url()).searchParams.get('returnTo') ?? '').includes('tab=history'), 'client History workout carries its selected tab in the URL')
    await reloadWithoutState()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('tab', { name: 'History', exact: true, selected: true }).waitFor()
    ok(new URL(page.url()).pathname === '/train', 'client workout returns to History after refresh with storage and history unavailable')
    await page.goto(BASE + '/train?tab=plan', { waitUntil: 'networkidle' })
    await page.getByRole('button', { name: dateLabel, exact: true }).click()
    await page.waitForURL(url => url.searchParams.get('date') === selectedDate)
    await page.locator('a[href^="/workout/' + scheduleId + '"]').first().click()
    await reloadWithoutState()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('tab', { name: 'Schedule', exact: true, selected: true }).waitFor()
    ok(new URL(page.url()).searchParams.get('date') === selectedDate, 'Schedule return keeps the selected training day')
    await page.locator('a[href^="/workout/' + scheduleId + '"]').first().waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'client training return fits phone width')
    await page.getByRole('button', { name: 'Build my own', exact: true }).click()
    await page.waitForURL(/\/build\//)
    clientBuiltWorkout = new URL(page.url()).pathname.split('/').pop()
    ok((new URL(page.url()).searchParams.get('returnTo') ?? '').includes('date=' + selectedDate), 'client builder keeps its source training day')
    await reloadWithoutState()
    await page.getByLabel('Name', { exact: true }).fill('Client navigation test')
    await page.getByRole('button', { name: 'Save workout', exact: true }).click()
    await page.waitForURL(/\/workout\//)
    await reloadWithoutState()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('tab', { name: 'Schedule', exact: true, selected: true }).waitFor()
    ok(new URL(page.url()).searchParams.get('date') === selectedDate, 'saving a personal workout keeps its original Schedule return route')
    await page.goto(BASE + '/', { waitUntil: 'networkidle' })
    await page.locator('a[href^="/workout/' + homeId + '"]').click()
    await reloadWithoutState()
    await page.getByRole('button', { name: 'Back', exact: true }).click()
    // '/' redirects to '/home', so accept either and wait for the Home screen itself.
    await page.waitForURL(url => url.pathname === '/' || url.pathname === '/home')
    await page.getByText('Habits', { exact: true }).first().waitFor()
    ok(['/', '/home'].includes(new URL(page.url()).pathname), 'workout opened from client Home returns to Home after refresh')
    clean('client tab memory and detail returns', client.errors)
  } finally {
    await client.ctx.close()
    await sql("delete from client_workouts where id::text like 'cf200000-0000-4000-8000-%'")
    if (clientBuiltWorkout) await sql('delete from workouts where id=$1', [clientBuiltWorkout])
    await sql('delete from client_health where client_id=$1', [IDS.ana])
  }
  const blocked = await open('coach')
  try {
    await blocked.page.addInitScript(() => Object.defineProperty(window, 'sessionStorage', { configurable: true, get() { throw new DOMException('Blocked', 'SecurityError') } }))
    await blocked.page.goto(BASE + '/library', { waitUntil: 'networkidle' })
    await blocked.page.getByRole('tab', { name: 'Exercises', exact: true }).click()
    await blocked.page.reload({ waitUntil: 'networkidle' })
    ok(await selected(blocked.page, 'Exercises') === 'true', 'tabs remain usable via URL with browser storage blocked')
    await blocked.page.getByRole('tab', { name: 'Programmes', exact: true }).click()
    await blocked.page.getByRole('link', { name: /^(Edit|View) and assign$/ }).first().click()
    const directProgramme = blocked.page.url().split('?')[0]
    await blocked.page.goto(directProgramme, { waitUntil: 'networkidle' })
    ok((await blocked.page.getByRole('link', { name: 'Back', exact: true }).getAttribute('href')).includes('tab=programs'), 'direct programme entry has an explicit Programmes return target without storage')
    await blocked.page.getByRole('link', { name: 'Back', exact: true }).click()
    await blocked.page.getByRole('tab', { name: 'Programmes', exact: true, selected: true }).waitFor()
    ok(await selected(blocked.page, 'Programmes') === 'true', 'View and assign returns to Programmes with browser storage blocked')
    await blocked.page.getByRole('link', { name: /^(Edit|View) and assign$/ }).first().click()
    await blocked.page.getByRole('button', { name: 'Week 2', exact: true }).click()
    await blocked.page.locator('a[href^="/library/workouts/"]').first().click()
    ok((new URL(blocked.page.url()).searchParams.get('returnTo') ?? '').includes('week=2'), 'nested workout carries return context in its URL')
    await blocked.page.evaluate(() => history.replaceState(null, '', location.href))
    await blocked.page.reload({ waitUntil: 'networkidle' })
    const nestedBack = blocked.page.getByRole('link', { name: 'Back', exact: true })
    ok((await nestedBack.getAttribute('href')).includes('/library/programs/') && (await nestedBack.getAttribute('href')).includes('week=2'), 'workout return target retains the originating programme and week after refresh')
    await nestedBack.click()
    await blocked.page.getByRole('button', { name: 'Week 2', exact: true }).waitFor()
    ok((await blocked.page.getByRole('button', { name: 'Week 2', exact: true }).getAttribute('class')).includes('on'), 'workout back returns to the selected programme week without storage')
    await blocked.page.getByRole('link', { name: 'Back', exact: true }).click()
    await blocked.page.getByRole('tab', { name: 'Programmes', exact: true, selected: true }).waitFor()
    await blocked.page.getByRole('tab', { name: 'Workouts', exact: true }).click()
    const workoutSearch = blocked.page.getByPlaceholder('Search workouts')
    const firstWorkoutName = await blocked.page.locator('.card a[href^="/library/workouts/"]:not(.btn)').first().innerText()
    await workoutSearch.fill(firstWorkoutName)
    await blocked.page.evaluate(() => { document.body.style.minHeight = '3000px'; scrollTo(0, 240) })
    await blocked.page.locator('.card a.btn[href^="/library/workouts/"]').first().click()
    const workoutReturn = new URL(blocked.page.url()).searchParams.get('returnTo') ?? ''
    ok(workoutReturn.includes('workoutQ=') && workoutReturn.includes('scrollY='), 'workout detail carries the Library search and scroll position')
    await blocked.page.reload({ waitUntil: 'networkidle' })
    await blocked.page.getByRole('link', { name: 'Back', exact: true }).click()
    await blocked.page.getByRole('tab', { name: 'Workouts', exact: true, selected: true }).waitFor()
    ok(await selected(blocked.page, 'Workouts') === 'true' && await workoutSearch.inputValue() === firstWorkoutName, 'workout details return to the same filtered Library view without storage')
    await blocked.page.setViewportSize({ width: 1280, height: 860 })
    for (const tab of ['Exercises', 'Programmes', 'Workouts']) {
      await blocked.page.getByRole('tab', { name: tab, exact: true }).click()
      await blocked.page.locator('nav a[href="/account"]').first().click()
      await blocked.page.locator('nav a[href="/library"]').first().click()
      await blocked.page.getByRole('tab', { name: tab, exact: true, selected: true }).waitFor()
      ok(await selected(blocked.page, tab) === 'true', tab + ' survives an unrelated page and menu return when storage is unavailable')
    }
    clean('blocked tab preference storage', blocked.errors)
  } finally { await blocked.ctx.close() }
}

